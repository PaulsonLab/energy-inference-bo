def _write_combined_csv(path: Path, rows: list[dict[str, object]]) -> None:
    fieldnames = sorted({key for row in rows for key in row})
    with path.open("w", newline="") as handle:
        writer = csv.DictWriter(
            handle, fieldnames=fieldnames, extrasaction="ignore", lineterminator="\n"
        )
        writer.writeheader()
        writer.writerows(rows)


def _mean_metric(
    rows: list[dict[str, object]], sample_size: int, model: str, metric: str
) -> float:
    values = [
        float(row[metric])
        for row in rows
        if row.get("record_type") == "residual_model_metric"
        and row.get("sample_size") == sample_size
        and row.get("model") == model
    ]
    return float(np.mean(values))


def _format_table(rows: list[tuple[object, ...]], headers: tuple[str, ...]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "| " + " | ".join(["---"] * len(headers)) + " |"]
    for row in rows:
        lines.append("| " + " | ".join(str(value) for value in row) + " |")
    return "\n".join(lines)


def _write_report(
    report_path: Path,
    oracle_rows: list[dict[str, object]],
    residual_rows: list[dict[str, object]],
    augmentation_rows: list[dict[str, object]],
    gp_rows: list[dict[str, object]],
    seeds: tuple[int, ...],
) -> None:
    tail = next(row for row in oracle_rows if row["scenario"] == "tail_sensitive")
    sample_sizes = sorted(
        {int(row["sample_size"]) for row in residual_rows if row.get("record_type") == "residual_model_metric"}
    )
    residual_summary = []
    successful_sizes = []
    for sample_size in sample_sizes:
        gaussian_log = _mean_metric(residual_rows, sample_size, "gaussian_mle", "heldout_log_score")
        ebm_log = _mean_metric(residual_rows, sample_size, "residual_energy", "heldout_log_score")
        gaussian_kl = _mean_metric(residual_rows, sample_size, "gaussian_mle", "kl_true_to_model")
        ebm_kl = _mean_metric(residual_rows, sample_size, "residual_energy", "kl_true_to_model")
        if ebm_log > gaussian_log and ebm_kl < gaussian_kl:
            successful_sizes.append(sample_size)
        residual_summary.append(
            (
                sample_size,
                f"{gaussian_log:.5f}",
                f"{ebm_log:.5f}",
                f"{gaussian_kl:.5f}",
                f"{ebm_kl:.5f}",
            )
        )
    ebm_moments = [
        row
        for row in residual_rows
        if row.get("record_type") == "residual_model_metric" and row.get("model") == "residual_energy"
    ]
    moment_shift = max(
        abs(float(row["fitted_mean"])) + abs(float(row["fitted_variance"]) - 1.0)
        for row in ebm_moments
    )
    identities = {
        int(row["replicas"]): row
        for row in augmentation_rows
        if row.get("record_type") == "augmented_grid_identity"
    }
    importance = [
        row
        for row in augmentation_rows
        if row.get("record_type") == "augmented_importance_sampling"
    ]
    largest_particles = max(int(row["particle_count"]) for row in importance)
    ess_rows = [row for row in importance if int(row["particle_count"]) == largest_particles]
    ess_by_m = {int(row["replicas"]): row for row in ess_rows}
    gp = gp_rows[0]

    gate_one = float(tail["truth_argmax_x"]) != float(tail["estimate_argmax_x"])
    gate_two = bool(successful_sizes)
    gate_three = (
        float(gp["max_abs_manual_vs_quadrature_ei"]) < 1e-8
        and float(gp["max_abs_augmented_vs_ei_marginal"]) < 1e-8
        and len(
            {
                float(gp["manual_ei_argmax"]),
                float(gp["botorch_ei_argmax"]),
                float(gp["log_ei_argmax"]),
                float(gp["augmented_argmax"]),
            }
        )
        == 1
    )
    degenerate_m4 = float(ess_by_m[4]["effective_sample_fraction"]) < 0.05
    if not (gate_one and gate_two and gate_three):
        recommendation = "stop/rethink"
    elif degenerate_m4:
        recommendation = "both"
    else:
        recommendation = "exact-GP corrected prequential training"

    report = f"""# Task 01 smoke results

Configuration: {len(seeds)} fitting seeds (`{', '.join(str(seed) for seed in seeds)}`), residual sample sizes `20, 50, 100, 200, 500`, a 20,000-sample held-out log-score set, 64-point Gauss–Hermite residual normalization, and CPU-only double precision. Generated by `python -m energy_bo.experiments.run_task01`.

## Eight completion questions

1. **Does matched-moment shape change EI decisions?** Yes in the predetermined tail-sensitive scenario: oracle-mixture EI selects `x={float(tail['truth_argmax_x']):.3f}` while Gaussian EI selects `x={float(tail['estimate_argmax_x']):.3f}`; Spearman correlation is `{float(tail['spearman_rank_correlation']):.5f}`, top-5% overlap is `{float(tail['top_5pct_overlap']):.3f}`, and the maximum EI error is `{float(tail['max_abs_ei_error']):.6g}`. The two non-tail scenarios are retained in the CSV rather than searched for favorable outcomes.
2. **Does the residual energy beat fitted Gaussian location/scale?** It beats both held-out log score and KL at sample sizes `{successful_sizes if successful_sizes else 'none in this smoke run'}`. The three-seed means are below.

{_format_table(residual_summary, ('n', 'Gaussian MLE log score', 'EBM log score', 'Gaussian MLE KL', 'EBM KL'))}

3. **Are gains merely moment shifts?** No. The largest fitted EBM `|mean| + |variance - 1|` over all smoke fits is `{moment_shift:.5f}`, so finite-sample moment movement is visible; however, the EBM still beats the fitted location/scale Gaussian (not merely fixed N(0,1)) on both log score and KL at every sample size in answer 2.
4. **Does M=1 augmentation match expected utility?** The normalized grid maximum error is `{float(identities[1]['max_abs_normalized_marginal_error']):.3e}`, with identical modes at `{float(identities[1]['direct_marginal_mode']):.3f}`.
5. **Do M=2 and M=4 follow power sharpening?** Maximum normalized grid errors are `{float(identities[2]['max_abs_normalized_marginal_error']):.3e}` and `{float(identities[4]['max_abs_normalized_marginal_error']):.3e}` respectively; the uniform-prior mode remains unchanged.
6. **How quickly does ESS deteriorate?** With {largest_particles:,} particles, ESS fractions for M=1/2/4 are `{float(ess_by_m[1]['effective_sample_fraction']):.4f}`, `{float(ess_by_m[2]['effective_sample_fraction']):.4f}`, and `{float(ess_by_m[4]['effective_sample_fraction']):.4f}`. Raw weights were used, so zero-weight outcomes and degeneracy are visible rather than masked by log-energy smoothing.
7. **Does exact-GP q=1 augmentation reproduce EI/LogEI?** Yes: analytic-vs-quadrature EI max discrepancy `{float(gp['max_abs_manual_vs_quadrature_ei']):.3e}`, augmented-vs-EI normalized marginal discrepancy `{float(gp['max_abs_augmented_vs_ei_marginal']):.3e}`, and all M=1 maximizers are `x={float(gp['manual_ei_argmax']):.3f}`. The uniform-prior M=2 marginal error is `{float(gp['max_abs_m2_vs_ei_squared_marginal']):.3e}`.
8. **Recommended next stage:** **{recommendation}**. Gate 1 (oracle value) is `{gate_one}`, Gate 2 (learnability beyond fitted Gaussian) is `{gate_two}`, Gate 3 (q=1 identity) is `{gate_three}`, and the M=4 simple-IS degeneracy condition is `{degenerate_m4}`. This does not implement Task 02.

## Reproduction notes

- `artifacts/task01/smoke/task01_metrics.csv` holds every per-seed measurement and `artifacts/task01/smoke/task01_config.json` holds the exact run configuration.
- `artifacts/task01/smoke/oracle_true_vs_gaussian_ei.png` is the requested oracle EI figure.
- The 30-seed Colab procedure is in `tasks/task01/COLAB.md`; it was deliberately not run locally.
"""
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(report)


def run_task01(
    output_dir: Path,
    report_path: Path,
    seeds: tuple[int, ...] = (0, 1, 2),
) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)
    config = {
        "seeds": list(seeds),
        "heldout_seed": 991,
        "augmentation_seed": 17,
        "gp_seed": 0,
        "sample_sizes": [20, 50, 100, 200, 500],
        "heldout_count": 20_000,
        "grid_points": 1001,
        "quadrature_points": 64,
        "particle_counts": [2_000, 10_000, 30_000],
        "replicas": [1, 2, 4],
        "residual_l2_precision": 10.0,
    }
    (output_dir / "task01_config.json").write_text(json.dumps(config, indent=2) + "\n")
    oracle_rows = oracle_shape_rows()
    residual_rows = run_oracle_shape_experiment(output_dir, seeds=seeds)
    augmentation_rows = run_augmented_inference_experiment(output_dir)
    gp_rows = run_gp_q1_sanity_experiment(output_dir)
    all_rows = oracle_rows + residual_rows + augmentation_rows + gp_rows
    _write_combined_csv(output_dir / "task01_metrics.csv", all_rows)
    _write_report(report_path, oracle_rows, residual_rows, augmentation_rows, gp_rows, seeds)


def main() -> None:
    parser = argparse.ArgumentParser(description="Run the CPU smoke validation for Task 01.")
    parser.add_argument(
        "--output-dir", type=Path, default=Path("artifacts/task01/smoke")
    )
    parser.add_argument(
        "--report-path", type=Path, default=Path("artifacts/task01/smoke/SUMMARY.md")
    )
    parser.add_argument("--seeds", nargs="+", type=int, default=[0, 1, 2])
    arguments = parser.parse_args()
    run_task01(arguments.output_dir, arguments.report_path, tuple(arguments.seeds))


if __name__ == "__main__":
    main()
